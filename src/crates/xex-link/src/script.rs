//! The GNU ld script that places the sections of a module for its
//! manifest.

use crate::layout::page_size;
use crate::manifest::Manifest;

/// The script for `manifest`. The first page of the image holds the headers
/// that xex-link synthesizes, so code starts one page above the load
/// address. Code, read-only data, writable data and zero-initialized data
/// each start on a page of their own, because the loader protects whole
/// pages. The import thunks follow the code: the loader rewrites them in
/// place, and they run as code. The data import slots follow the data.
pub fn link_script(manifest: &Manifest) -> String {
    let base = manifest.load_address.0;
    let page = page_size(manifest.image_flags);
    format!(
        "\
/* Generated by xex-link link-script. */
ENTRY(_start)

SECTIONS {{
    . = {code:#x};
    .text : {{
        *(.text._start)
        *(.text .text.*)
    }}
    . = ALIGN(4);
    .xthunks : {{ *(.xthunks .xthunks.*) }}

    . = ALIGN({page:#x});
    .rodata : {{ *(.rodata .rodata.*) }}

    . = ALIGN({page:#x});
    .init_array : {{ KEEP(*(.init_array .init_array.*)) }}
    .data : {{ *(.data .data.*) *(.sdata .sdata.*) }}
    .xvars : {{ *(.xvars .xvars.*) }}

    . = ALIGN({page:#x});
    .bss : {{ *(.bss .bss.*) *(.sbss .sbss.*) *(COMMON) }}

    /DISCARD/ : {{ *(.eh_frame) *(.eh_frame_hdr) *(.comment) *(.note .note.*) }}
}}
",
        code = base + page,
    )
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    #[test]
    fn code_starts_one_page_above_the_load_address() {
        let script = link_script(&Manifest::default());
        assert!(script.contains(". = 0x82010000;"), "{script}");
        assert!(script.contains("ALIGN(0x10000)"), "{script}");

        let manifest = Manifest::parse(
            Path::new("xex.toml"),
            "load_address = 0x91d00000\nimage_flags = [\"SMALL_PAGES\"]",
        )
        .unwrap();
        let script = link_script(&manifest);
        assert!(script.contains(". = 0x91d01000;"), "{script}");
        assert!(script.contains("ALIGN(0x1000)"), "{script}");
        assert!(!script.contains("ALIGN(0x10000)"), "{script}");
    }
}
