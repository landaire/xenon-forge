//! Raw bindings to the Xbox 360 kernel and XAM for the
//! `powerpc-unknown-xbox360` target: imports, exports, entries for callers
//! that use the console ABI, the interlocked operations the kernel loader
//! accepts, and the types and constants of the import signatures.
//!
//! The C headers of the SDK in `src/sdk/include/xbox360` are the source of
//! truth for the imports. Each import is declared with
//! `XBOX360_IMPORT(library, ordinal)`. `src/tools/xbox360-bindgen` runs
//! bindgen on the headers to make [`ffi`], and reads the annotations to make
//! the thunk library in `src/sdk/thunks`, which this crate assembles and C
//! titles link. For each function import, the library has a function under
//! the import's own name, so C and Rust call it as a plain `extern "C"`
//! function. For each data import, it has the slot `__imp_<name>`.
//!
//! Each import is a 16-byte thunk in its own `.xthunks.*` section. The first
//! big-endian DWORD is the import record `(type<<24 | lib<<16 | ordinal)`.
//! `xex-link` collects these into the XEX `ImportLibraries` table, and at load
//! time Xenia (and a real console) rewrites the thunk to a syscall trap. The
//! remaining DWORDs (`nop; nop; blr`) are only a fallback if never patched.
//!
//! The powerpc64 ILP32 code generation calls with the console convention,
//! so there the function is the thunk. The powerpc (SysV) code generation
//! does not: console callees home r3-r10 into a caller frame area that SysV
//! frames do not reserve, and take a 64-bit value in one register. There
//! the function is a stub that opens a frame with that area, moves the
//! arguments to where the export reads them and calls the thunk.
//!
//! The typed declarations of [`xboxkrnl`] and [`xam`] link to the same
//! functions. A compile-time check compares each with its C declaration in
//! [`ffi`]: the same argument count, and the same width class for each
//! argument and the result.
//!
//! Console callers expect r14-r31 preserved in full 64 bits. Code for this
//! target saves only their low words, so code that the kernel, the loader or
//! another module calls (an entry point, an export, a thread start routine,
//! a callback) enters through [`entry_bridge`], which [`bridged!`] and
//! [`export!`] arrange.
//!
//! Types, constants, structure layouts and [`status`] compile on every
//! target, so host code can share them. Imports, the functions of
//! [`processor`], [`mmio`], [`interlocked`] and the entry bridge exist only
//! for `target_os = "xbox360"`. Documentation builds them on another
//! PowerPC target with `--cfg xbox360_docs`.
//!
//! Every type in an import signature passes like the C integer of its
//! width: enums are `#[repr(u32)]` (or the C width), and newtypes are
//! `#[repr(transparent)]`. Values the kernel returns are newtypes, so an
//! unknown value is never undefined behaviour.
//!
//! Imports are `unsafe extern "C" fn`. The few that take no address or
//! object the kernel uses and have no effect that safe code relies on are
//! declared `safe` and are plain `extern "C" fn`.

