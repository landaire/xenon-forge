//! Generates the Rust bindings of xbox360-sys and the import thunks of the
//! SDK from the SDK's C headers.
//!
//! The headers in `src/sdk/include` are the source of truth. bindgen turns
//! them into xbox360-sys's `src/ffi.rs`. The imports they annotate with
//! `XBOX360_IMPORT` become the thunk library, `src/sdk/thunks/ppc32.S` and
//! `src/sdk/thunks/ppc64.S`, which C and Rust code link to call the imports
//! as plain `extern "C"` functions.

mod imports;
mod thunks;

use std::fs;
use std::path::Path;
use std::path::PathBuf;
use std::process::ExitCode;

use clap::Parser;

/// Generate the Rust bindings and import thunks of xbox360-sys.
#[derive(Parser)]
struct Args {
    /// Directory that holds `xbox360/`, passed to clang with `-I`.
    #[arg(long, default_value_os_t = repo_path("src/sdk/include"))]
    include: PathBuf,

    /// Header that includes every other header.
    #[arg(long, default_value_os_t = repo_path("src/sdk/include/xbox360/xbox360.h"))]
    header: PathBuf,

    /// Rust bindings to write.
    #[arg(long, default_value_os_t = repo_path("src/crates/xbox360-sys/src/ffi.rs"))]
    rust: PathBuf,

    /// Thunks for the powerpc (SysV) code generation.
    #[arg(long, default_value_os_t = repo_path("src/sdk/thunks/ppc32.S"))]
    thunks_ppc32: PathBuf,

    /// Thunks for the powerpc64 ILP32 code generation.
    #[arg(long, default_value_os_t = repo_path("src/sdk/thunks/ppc64.S"))]
    thunks_ppc64: PathBuf,

    /// Fail if an output differs from what the headers give, instead of
    /// writing it.
    #[arg(long)]
    check: bool,
}

/// `path` relative to the repository root.
fn repo_path(path: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../..")
        .join(path)
}

/// Clang arguments of every parse. The thunks and the bindings use the
/// powerpc target: its C types have the sizes and alignments of the
/// powerpc64 ILP32 target.
fn clang_args(include: &Path) -> Vec<String> {
    vec![
        "--target=powerpc-unknown-none-eabi".to_owned(),
        "-ffreestanding".to_owned(),
        "-nostdinc".to_owned(),
        "-std=c11".to_owned(),
        format!("-I{}", include.display()),
    ]
}

fn bindings(args: &Args, include: &Path) -> Result<String, String> {
    let header = args.header.to_str().ok_or("the header path is not UTF-8")?;
    let files = format!(
        "{}/.*",
        escape_regex(include.to_str().ok_or("the include path is not UTF-8")?)
    );
    let bindings = bindgen::Builder::default()
        .header(header)
        .clang_args(clang_args(include))
        .allowlist_file(files)
        // Defined by C modules, not imported.
        .blocklist_function("DllMain")
        .use_core()
        .ctypes_prefix("core::ffi")
        // xbox360-sys's rust-version.
        .rust_target(
            bindgen::RustTarget::stable(95, 0).map_err(|error| format!("bindgen: {error}"))?,
        )
        .rust_edition(bindgen::RustEdition::Edition2024)
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        .enable_function_attribute_detection()
        .generate_comments(true)
        .layout_tests(true)
        .merge_extern_blocks(true)
        .wrap_unsafe_ops(true)
        .formatter(bindgen::Formatter::Prettyplease)
        .raw_line(GENERATED_RUST)
        .generate()
        .map_err(|error| format!("bindgen: {error}"))?;
    Ok(bindings.to_string())
}

const GENERATED_RUST: &str =
    "// @generated by src/tools/xbox360-bindgen from src/sdk/include. Do not edit.";

fn escape_regex(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for c in text.chars() {
        if "\\.+*?()|[]{}^$#&-~".contains(c) {
            escaped.push('\\');
        }
        escaped.push(c);
    }
    escaped
}

/// Write `contents` to `path`, or with `check`, report whether it differs.
fn emit(path: &Path, contents: &str, check: bool) -> Result<bool, String> {
    if check {
        let current = fs::read_to_string(path).unwrap_or_default();
        if current != contents {
            eprintln!("{} is out of date", path.display());
            return Ok(false);
        }
        return Ok(true);
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|error| format!("{}: {error}", parent.display()))?;
    }
    fs::write(path, contents).map_err(|error| format!("{}: {error}", path.display()))?;
    Ok(true)
}

fn run(args: &Args) -> Result<bool, String> {
    let include = args
        .include
        .canonicalize()
        .map_err(|error| format!("{}: {error}", args.include.display()))?;
    let imports = imports::scan(&args.header, &include, &clang_args(&include))?;
    let rust = bindings(args, &include)?;
    let ppc32 = thunks::ppc32(&imports)?;
    let ppc64 = thunks::ppc64(&imports);

    let mut current = true;
    current &= emit(&args.rust, &rust, args.check)?;
    current &= emit(&args.thunks_ppc32, &ppc32, args.check)?;
    current &= emit(&args.thunks_ppc64, &ppc64, args.check)?;
    Ok(current)
}

fn main() -> ExitCode {
    let args = Args::parse();
    match run(&args) {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => {
            eprintln!("run src/tools/xbox360-bindgen to regenerate");
            ExitCode::FAILURE
        }
        Err(error) => {
            eprintln!("xbox360-bindgen: {error}");
            ExitCode::FAILURE
        }
    }
}
