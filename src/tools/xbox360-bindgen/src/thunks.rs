//! The thunk library: for each function import a function under its own
//! name that calls the 16-byte import thunk, and for each data import its
//! slot. The output is one invocation per import of the macros in
//! `src/sdk/thunks/macros.inc`.
//!
//! The loader rewrites each thunk to call the export. The export uses the
//! console calling convention: every argument has an 8-byte slot, the
//! first eight in r3-r10 and the rest at sp+0x50 of the caller, a 64-bit
//! integer in one register, floating-point arguments in f1-f13 while still
//! taking their slot, and a caller-reserved home area for r3-r10 at
//! sp+0x10..sp+0x50.
//!
//! powerpc64 ILP32 code calls with that convention, so there the function
//! is the thunk itself. powerpc (SysV) code does not: it reserves no home
//! area, passes a 64-bit integer in a register pair, the ninth argument at
//! sp+8, and floating-point arguments without a GPR. The ppc32 function
//! opens a frame with the home area, moves the arguments to where the
//! export reads them and calls the thunk.

use std::fmt::Write;

use crate::imports::Function;
use crate::imports::Import;
use crate::imports::ImportKind;
use crate::imports::Scalar;

/// The macros are included by the C preprocessor for C titles. Rust code,
/// which assembles the file without it, puts them in front itself, and
/// reads the `#include` line as a comment.
const HEADER: &str = "/* @generated by src/tools/xbox360-bindgen from src/sdk/include. Do not edit. */\n\
                      #include \"macros.inc\"\n\n";

/// Home area of the export and the linkage area below it.
const HOME_END: u32 = 0x50;

pub fn ppc64(imports: &[Import]) -> String {
    let mut out = String::from(HEADER);
    for import in imports {
        let (name, record) = (&import.name, import.record());
        let _ = match &import.kind {
            // The caller already reserves the home area.
            ImportKind::Function(function) if function.noreturn => {
                writeln!(out, "xbox360_noreturn {name}, {record:#010x}, 0")
            }
            ImportKind::Function(_) => writeln!(out, "xbox360_thunk {name}, {record:#010x}"),
            ImportKind::Variable => writeln!(out, "xbox360_slot {name}, {record:#010x}"),
        };
    }
    out
}

pub fn ppc32(imports: &[Import]) -> Result<String, String> {
    let mut out = String::from(HEADER);
    for import in imports {
        let (name, record) = (&import.name, import.record());
        let function = match &import.kind {
            ImportKind::Function(function) => function,
            ImportKind::Variable => {
                let _ = writeln!(out, "xbox360_slot {name}, {record:#010x}");
                continue;
            }
        };
        let (frame, moves) = ppc32_stub(function).map_err(|error| format!("{name}: {error}"))?;
        let kind = result_kind(function.result);
        if moves.is_empty() && frame == HOME_END {
            let _ = match (function.noreturn, kind) {
                (true, _) => writeln!(out, "xbox360_noreturn {name}, {record:#010x}"),
                (false, "word") => writeln!(out, "xbox360_stub {name}, {record:#010x}"),
                (false, kind) => writeln!(out, "xbox360_stub {name}, {record:#010x}, {kind}"),
            };
            continue;
        }

        let _ = writeln!(out, "\n.ifndef {name}");
        let _ = writeln!(out, "\txbox360_function {name}");
        let _ = writeln!(out, "\txbox360_frame {frame:#x}");
        for instruction in moves {
            let _ = writeln!(out, "\t{instruction}");
        }
        let _ = writeln!(out, "\txbox360_call {name}");
        if function.noreturn {
            out.push_str("\ttrap\n");
        } else {
            if kind != "word" {
                let _ = writeln!(out, "\txbox360_result {kind}");
            }
            let _ = writeln!(out, "\txbox360_return {frame:#x}");
        }
        let _ = writeln!(out, "\txbox360_end {name}, {record:#010x}\n.endif\n");
    }
    Ok(out)
}

/// The `kind` of `xbox360_result` for a result.
fn result_kind(result: Option<Scalar>) -> &'static str {
    match result {
        Some(Scalar::Int64) => "u64",
        Some(Scalar::Int {
            size: 1,
            signed: false,
        }) => "u8",
        Some(Scalar::Int {
            size: 2,
            signed: false,
        }) => "u16",
        Some(Scalar::Int {
            size: 1,
            signed: true,
        }) => "i8",
        Some(Scalar::Int {
            size: 2,
            signed: true,
        }) => "i16",
        _ => "word",
    }
}

/// Where a SysV caller leaves an argument.
#[derive(Clone, Copy)]
enum Source {
    Gpr(u32),
    /// High word in the first register.
    GprPair(u32),
    Fpr(u32),
    /// Offset from the caller's stack pointer.
    Stack(u32),
}

/// Where the export reads an argument.
#[derive(Clone, Copy)]
enum Destination {
    Gpr(u32),
    Fpr(u32),
    /// Offset from the stub's stack pointer.
    Stack(u32),
}

/// Where a word of an argument is before the moves.
enum Word {
    Register(u32),
    Memory(u32),
}

/// The frame size of the SysV stub and the moves that put the arguments
/// where the export reads them.
fn ppc32_stub(function: &Function) -> Result<(u32, Vec<String>), String> {
    if function.variadic {
        // The SysV and console conventions agree for 32-bit integer
        // arguments in r3-r10, so they pass through.
        if let Some(parameter) = function
            .parameters
            .iter()
            .find(|p| !matches!(p, Scalar::Int { .. }))
        {
            return Err(format!(
                "variadic import with a fixed {parameter:?} parameter"
            ));
        }
        return Ok((HOME_END, Vec::new()));
    }

    let sources = sysv_sources(&function.parameters)?;
    let destinations = console_destinations(&function.parameters)?;
    let slots = function.parameters.len().saturating_sub(8) as u32;
    let frame = (HOME_END + 8 * slots).next_multiple_of(16);

    let identity = |index: usize| {
        matches!(
            (function.parameters[index], sources[index], destinations[index]),
            (Scalar::Int { .. }, Source::Gpr(from), Destination::Gpr(to)) if from == to
        )
    };
    // When a move writes an argument register, every register that moves
    // goes through the home area first. The export only writes it after
    // the call.
    let spill = (0..function.parameters.len())
        .any(|index| matches!(destinations[index], Destination::Gpr(_)) && !identity(index));

    let mut moves = Vec::new();
    if spill {
        for (index, source) in sources.iter().enumerate() {
            match *source {
                _ if identity(index) => {}
                Source::Gpr(register) => moves.push(format!(
                    "stw {}, {:#x}(1)",
                    3 + register,
                    spill_offset(register)
                )),
                Source::GprPair(register) => {
                    moves.push(format!(
                        "stw {}, {:#x}(1)",
                        3 + register,
                        spill_offset(register)
                    ));
                    moves.push(format!(
                        "stw {}, {:#x}(1)",
                        4 + register,
                        spill_offset(register + 1)
                    ));
                }
                Source::Fpr(_) | Source::Stack(_) => {}
            }
        }
    }
    let word = |source: Source, word: u32| match source {
        Source::Gpr(register) | Source::GprPair(register) if spill => {
            Word::Memory(spill_offset(register + word))
        }
        Source::Gpr(register) | Source::GprPair(register) => Word::Register(3 + register + word),
        Source::Stack(offset) => Word::Memory(frame + offset + 4 * word),
        Source::Fpr(_) => unreachable!("a floating-point argument has no words"),
    };

    for (index, parameter) in function.parameters.iter().enumerate() {
        let source = sources[index];
        match (destinations[index], *parameter) {
            (Destination::Stack(offset), Scalar::Int { .. }) => {
                moves.push("li 12, 0".to_owned());
                moves.push(format!("stw 12, {offset:#x}(1)"));
                store_word(&mut moves, word(source, 0), offset + 4);
            }
            (Destination::Stack(offset), Scalar::Int64) => {
                store_word(&mut moves, word(source, 0), offset);
                store_word(&mut moves, word(source, 1), offset + 4);
            }
            (Destination::Stack(_), _) => {
                return Err(format!(
                    "parameter {} is a floating-point argument on the stack",
                    index + 1
                ));
            }
            (Destination::Gpr(_), Scalar::Int { .. }) if identity(index) => {}
            (Destination::Gpr(register), Scalar::Int { .. }) => {
                load_word(&mut moves, word(source, 0), 3 + register);
            }
            (Destination::Gpr(register), Scalar::Int64) => {
                load_word(&mut moves, word(source, 1), 3 + register);
                load_word(&mut moves, word(source, 0), 11);
                moves.push(format!("rldimi {}, 11, 32, 0", 3 + register));
            }
            (Destination::Fpr(to), scalar) => match source {
                Source::Fpr(from) if from == to => {}
                Source::Stack(offset) if scalar == Scalar::Double => {
                    moves.push(format!("lfd {}, {:#x}(1)", 1 + to, frame + offset));
                }
                _ => {
                    return Err(format!(
                        "parameter {} moves between floating-point registers",
                        index + 1
                    ));
                }
            },
            (Destination::Gpr(_), _) => {
                unreachable!("floating-point arguments go to FPRs or the stack")
            }
        }
    }

    Ok((frame, moves))
}

fn spill_offset(register: u32) -> u32 {
    0x10 + 4 * register
}

fn store_word(moves: &mut Vec<String>, word: Word, offset: u32) {
    match word {
        Word::Register(register) => moves.push(format!("stw {register}, {offset:#x}(1)")),
        Word::Memory(from) => {
            moves.push(format!("lwz 11, {from:#x}(1)"));
            moves.push(format!("stw 11, {offset:#x}(1)"));
        }
    }
}

fn load_word(moves: &mut Vec<String>, word: Word, register: u32) {
    match word {
        Word::Register(from) => moves.push(format!("mr {register}, {from}")),
        Word::Memory(from) => moves.push(format!("lwz {register}, {from:#x}(1)")),
    }
}

/// SysV locations: integers in r3-r10, a 64-bit integer in an aligned
/// register pair (r3:r4, r5:r6, r7:r8, r9:r10), floating-point values in
/// f1-f8, the rest from sp+8.
fn sysv_sources(parameters: &[Scalar]) -> Result<Vec<Source>, String> {
    let mut gpr = 0;
    let mut fpr = 0;
    let mut stack = 8;
    let mut sources = Vec::with_capacity(parameters.len());
    for (index, parameter) in parameters.iter().enumerate() {
        let source = match parameter {
            Scalar::Int { .. } if gpr < 8 => {
                gpr += 1;
                Source::Gpr(gpr - 1)
            }
            Scalar::Int { .. } => {
                stack += 4;
                Source::Stack(stack - 4)
            }
            Scalar::Int64 => {
                gpr += gpr % 2;
                if gpr < 8 {
                    gpr += 2;
                    Source::GprPair(gpr - 2)
                } else {
                    gpr = 8;
                    stack = stack.next_multiple_of(8) + 8;
                    Source::Stack(stack - 8)
                }
            }
            Scalar::Float | Scalar::Double if fpr < 8 => {
                fpr += 1;
                Source::Fpr(fpr - 1)
            }
            Scalar::Double => {
                stack = stack.next_multiple_of(8) + 8;
                Source::Stack(stack - 8)
            }
            Scalar::Float => {
                return Err(format!(
                    "parameter {} is a float on the SysV stack",
                    index + 1
                ));
            }
        };
        sources.push(source);
    }
    Ok(sources)
}

/// Console locations: one 8-byte slot per argument.
fn console_destinations(parameters: &[Scalar]) -> Result<Vec<Destination>, String> {
    let mut fpr = 0;
    let mut destinations = Vec::with_capacity(parameters.len());
    for (slot, parameter) in parameters.iter().enumerate() {
        let slot = slot as u32;
        let destination = match parameter {
            Scalar::Float | Scalar::Double if fpr < 13 => {
                fpr += 1;
                Destination::Fpr(fpr - 1)
            }
            _ if slot < 8 => Destination::Gpr(slot),
            _ => Destination::Stack(HOME_END + 8 * (slot - 8)),
        };
        destinations.push(destination);
    }
    Ok(destinations)
}
